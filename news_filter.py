# 个股代码：正文里出现 6 位股票代码视为强财经信号
CODE_RE = re.compile(r"\((?:S[HZ]|B[JS])?(\d{6})(?:\.(?:S[HZ]|BJ))?\)")


def _hits(text, words):
    return [w for w in words if w in text]


def classify(it):
    """返回 (keep: bool, cat: str, reason: str)。

    keep=True 时 cat 为 公司/科技/市场/宏观/国际/社会/产业 之一。
    keep=False 时 reason 说明剔除原因，供统计核对。
    """
    title = it.get("title") or ""
    content = it.get("content") or ""
    tags = " ".join(it.get("tags") or [])
    text = f"{title} {content} {tags}"

    # 0) 付费导流：标题里没有信息，正文是「解锁阅读」这类钩子
    if _hits(text, PAYWALL) and len(content) < 120:
        return False, "", "付费导流"
    if len(content) < 18 and len(title) < 8:
        return False, "", "内容过短"

    weather = _hits(text, WEATHER)
    impact = _hits(text, IMPACT)
    finance = _hits(text, FINANCE)
    social = _hits(text, SOCIAL)
    soft = _hits(text, DROP_SOFT)
    has_code = bool(CODE_RE.search(text))

    # 1) 纯天气：有气象词，但没有财经/影响/社会信号
    if weather and not impact and not finance and not social and not has_code:
        return False, "", f"纯天气（{'、'.join(weather[:2])}）"

    # 2) 财经 / 科技：有硬信号就收
    if finance or has_code:
        for name, words in TOPICS:
            if _hits(text, words):
                return True, name, ""
        return True, "市场", ""

    # 3) 社会重大影响
    if social:
        for name, words in TOPICS:
            if name in ("国际", "社会") and _hits(text, words):
                return True, name, ""
        return True, "社会", ""

    # 4) 气象 + 影响（没被前面收走，说明影响词不够财经向）
    if weather and impact:
        return True, "社会", ""

    # 5) 其余的娱乐 / 体育 / 生活服务，不收录
    if soft:
        return False, "", f"非财经（{'、'.join(soft[:2])}）"
    return False, "", "与财经科技无关"


def split(items):
    """把快讯分成 (保留, 剔除) 两组，保留的加 cat 字段。"""
    keep, drop = [], []
    for it in items:
        ok, cat, reason = classify(it)
        if ok:
            it2 = dict(it)
            it2["cat"] = cat
            keep.append(it2)
        else:
            drop.append({"title": (it.get("title") or "")[:40], "time": it.get("time"),
                         "reason": reason})
    return keep, drop


