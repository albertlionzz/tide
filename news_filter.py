def _selftest():
    bad = 0
    for title, body, want in _CASES:
        got, cat, reason = classify({"title": title, "content": body, "tags": []})
        mark = "ok " if got == want else "FAIL"
        if got != want:
            bad += 1
        print(f"  [{mark}] keep={got!s:<5} want={want!s:<5} {cat or reason:<16} {title[:34]}")
    print(f"自测 {len(_CASES) - bad}/{len(_CASES)} 通过")
    return 0 if bad == 0 else 1


